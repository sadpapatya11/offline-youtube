package com.offlineyoutube.offlineyoutube

import android.content.Context
import android.webkit.CookieManager
import android.util.Log
import java.io.File
import java.io.BufferedWriter
import java.io.OutputStreamWriter
import java.util.concurrent.ConcurrentHashMap

/**
 * yt-dlp'ye verilecek Netscape biçimli çerez dosyasını üretir.
 *
 * Dosya ZORUNLU olarak düz metindir: yt-dlp `--cookies` seçeneğiyle dosyayı kendisi
 * okur, yani şifreli bir kap kullanılamaz. Bu yüzden önceki sürümdeki
 * `androidx.security.crypto.EncryptedFile` ve `MasterKey` import'ları hiçbir zaman
 * kullanılmıyordu ve yanlış bir güvenlik hissi veriyordu; ikisi de kaldırıldı.
 *
 * Bunun yerine gerçek koruma iki şeye dayanır:
 *  1. Dosya uygulamaya özel [Context.getCacheDir] altında tutulur (0700) ve manifest'te
 *     `allowBackup="false"` olduğu için yedeğe girmez.
 *  2. Ömrü mümkün olan en kısa süreye indirilir: çağıran taraf iş bitince [release]
 *     çağırır, ayrıca [clearStaleCookieFiles] süreç öldürüldüğünde geride kalan
 *     artıkları bir sonraki açılışta temizler.
 */
object CookieHelper {
    private const val TAG = "CookieHelper"

    /** Ürettiğimiz her çerez dosyası bu önekle başlar; temizlik taraması buna bakar. */
    private const val COOKIE_FILE_PREFIX = "youtube_cookies"

    // FIX(cerez-yarisi): Çerez dosyası eskiden TEK sabit isimdeydi
    // ("youtube_cookies.txt"). Uzun bir indirme sürerken yapılan metadata veya
    // oynatma listesi çekimi saniyeler içinde bitip kendi `finally` bloğunda AYNI
    // dosyayı siliyordu: çalışan indirme çerezsiz kalıyor ve YouTube "Sign in to
    // confirm you're not a bot" ile indirmeyi kesiyordu. Artık her çağrı kendi
    // dosyasını üretir ve yalnız kendi dosyasını siler.
    //
    // [inUse] ayrıca açılıştaki süpürmenin ÇALIŞAN bir indirmenin çerezini silmesini
    // engeller: servis indirme sürerken kullanıcı uygulamayı kapatıp yeniden açarsa
    // configureFlutterEngine tekrar koşar ve süpürme yeniden tetiklenir.
    private val inUse = ConcurrentHashMap.newKeySet<String>()

    /**
     * @param owner çağrıyı ayırt eden anahtar (indirme görevi kimliği ya da "meta"
     *   gibi sabit bir etiket). Dosya adına girer, bu yüzden temizlenir.
     */
    fun saveCookies(context: Context, owner: String): File? {
        var cookieFile: File? = null
        try {
            val cookieManager = CookieManager.getInstance()
            val youtubeCookies = cookieManager.getCookie("https://youtube.com") ?: ""
            val googleCookies = cookieManager.getCookie("https://google.com") ?: ""

            if (youtubeCookies.isEmpty() && googleCookies.isEmpty()) return null

            // Aynı etiketle (ör. iki eşzamanlı "meta" çekimi) gelen çağrılar da
            // çakışmasın diye nanoTime ekleniyor.
            val safeOwner = owner.replace(Regex("[^A-Za-z0-9_-]"), "_").take(40)
            val file = File(
                context.cacheDir,
                "${COOKIE_FILE_PREFIX}_${safeOwner}_${System.nanoTime()}.txt"
            )
            cookieFile = file
            inUse.add(file.absolutePath)

            BufferedWriter(OutputStreamWriter(file.outputStream(), Charsets.UTF_8)).use { writer ->
                writer.write("# Netscape HTTP Cookie File\n")
                writer.write("# This file is generated by Offline YouTube.\n\n")

                fun writeCookiesForDomain(cookieStr: String, domain: String) {
                    if (cookieStr.isEmpty()) return
                    val pairs = cookieStr.split(";")
                    for (pair in pairs) {
                        val parts = pair.trim().split("=", limit = 2)
                        if (parts.size == 2) {
                            val name = parts[0]
                            val value = parts[1]
                            val flag = "TRUE"
                            val path = "/"
                            val secure = "TRUE"
                            val expiration = "2147483647"

                            writer.write("$domain\t$flag\t$path\t$secure\t$expiration\t$name\t$value\n")
                        }
                    }
                }

                writeCookiesForDomain(youtubeCookies, ".youtube.com")
                writeCookiesForDomain(googleCookies, ".google.com")
            }
            cookieManager.flush()

            Log.d(TAG, "Çerez dosyası yazıldı (düz metin, yt-dlp gereği); kullanım sonrası silinir")
            return file
        } catch (e: Exception) {
            Log.e(TAG, "Error saving cookies", e)
            // Yarım yazılmış dosya geride kalırsa oturum çerezleri diskte kalıcı olur.
            release(cookieFile)
            return null
        }
    }

    /**
     * Çağıranın kendi çerez dosyasını bitirdiğinde çağırdığı temizlik.
     *
     * Doğrudan `file.delete()` YETMEZ: dosya [inUse] kaydından düşmezse
     * [clearStaleCookieFiles] o yolu sonsuza dek "kullanımda" sayar.
     */
    fun release(file: File?) {
        if (file == null) return
        try {
            file.delete()
        } catch (e: Exception) {
            Log.w(TAG, "Çerez dosyası silinemedi: ${e.message}")
        } finally {
            inUse.remove(file.absolutePath)
        }
    }

    /**
     * Önceki koşulardan kalan çerez dosyalarını siler.
     *
     * Normal akışta çağıran taraf [release] ile siler, ama uygulama süreci öldürülürse
     * o blok hiç çalışmaz ve tam Google oturum çerezleri diskte kalır. Şu an kullanımda
     * olan dosyalara DOKUNULMAZ.
     */
    fun clearStaleCookieFiles(context: Context) {
        try {
            context.cacheDir.listFiles()?.forEach { f ->
                if (f.isFile && f.name.startsWith(COOKIE_FILE_PREFIX) && !inUse.contains(f.absolutePath)) {
                    f.delete()
                }
            }
        } catch (e: Exception) {
            Log.w(TAG, "Artık çerez dosyaları temizlenemedi: ${e.message}")
        }
    }
}
